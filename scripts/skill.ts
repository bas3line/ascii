// npm run gen (or node scripts/skill.ts on its own): writes the agent skill in
// skills/ascii-rest, which `npx skills add bas3line/ascii` installs and skills.sh
// lists. SKILL.md is scripts/skill/SKILL.md with the piece count and the docs'
// rules for agents filled in; references/ holds the piece catalog, from each
// piece's meta, and every docs page made plain, the way /llms-full.txt is. CI
// checks the folder is up to date, so a new piece or a docs edit needs gen run.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { Piece } from "../src/types.ts";
import { plain, section, split } from "../site/src/lib/plain.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = `${ROOT}skills/ascii-rest`;
const SITE = "https://ascii.rest";
// The docs' order of categories (pages/docs/index.md), which the site's sidebar follows too.
const CATEGORIES = ["scenes", "ui", "data", "type", "logos", "companies", "distros", "shapes", "space", "physics", "nature", "creatures", "objects", "generative", "effects"];

const { names } = (await import(pathToFileURL(`${ROOT}src/library.ts`).href)) as { names: string[] };
const camel = (slug: string) => slug.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const pieces = await Promise.all(
  names.map(async (slug) => ({ slug, ...((await import(pathToFileURL(`${ROOT}src/pieces/${slug}.ts`).href)) as Piece) })),
);
const order = [...CATEGORIES, ...new Set(pieces.map((p) => p.meta.category).filter((c) => !CATEGORIES.includes(c)))];
const cell = (s: string) => s.replace(/\|/g, "\\|");

const catalog = [
  `<!-- Generated by scripts/skill.ts from each piece's meta. Run npm run gen after adding one. -->`,
  `# Every piece`,
  ``,
  `${pieces.length} pieces. The name is what \`<Ascii piece="…">\`, \`<ascii-art piece="…">\`, and \`npx ascii.rest …\` take; the export is what \`import { … } from "ascii.rest/pieces"\` gives. A **canvas** piece has colours of its own and draws on a \`<canvas>\`: size it with \`width\`. A **text** piece draws in a \`<pre>\` in the page's colour: size it with \`font-size\`. Options are the piece's own, with their defaults; pass them as \`options\`. Each piece plays at ${SITE}/<name>/. Only logos, companies and distros have hosted README SVGs, at ${SITE}/svg/<name>.svg and .dark.svg; any other piece needs \`svg()\` from \`ascii.rest/svg\` and a committed file.`,
  ``,
  ...order.flatMap((category) => {
    const these = pieces.filter((p) => p.meta.category === category).sort((a, b) => a.slug.localeCompare(b.slug));
    if (!these.length) return [];
    return [
      `## ${category} (${these.length})`,
      ``,
      `| name | export | draws | size | fps | what you see | options |`,
      `| --- | --- | --- | --- | --- | --- | --- |`,
      ...these.map(({ slug, meta }) => {
        const options = meta.options && Object.keys(meta.options).length ? `\`${cell(JSON.stringify(meta.options))}\`` : "";
        const draws = meta.palette ? "canvas" : "text";
        return `| \`${slug}\` | \`${camel(slug)}\` | ${draws} | ${meta.cols}×${meta.rows} | ${meta.fps || "still"} | ${cell(meta.note)} | ${options} |`;
      }),
      ``,
    ];
  }),
].join("\n");

// Every docs page, plain, in the docs' order, as references/docs/<page>.md.
// The docs' index, loaded by path so the package's typecheck stays out of the site's code.
const { DOCS: groups } = (await import(pathToFileURL(`${ROOT}site/src/lib/docs.ts`).href)) as {
  DOCS: readonly { label: string; pages: readonly { href: string; title: string }[] }[];
};
const docs = groups.flatMap((group) => group.pages.map((p) => ({ ...p, group: group.label })));
const file = (href: string) => (href === "/docs/" ? "index" : href.slice("/docs/".length, -1));
const read = (href: string) => split(readFileSync(`${ROOT}site/src/pages/docs/${file(href)}.md`, "utf8"));

const rules = section(plain(read("/docs/").body, SITE), "Rules for AI coding agents").replace(/^If your agent can't read web pages, paste these rules into its prompt\.\n\n/, "");
if (!rules) throw new Error("skill: no \"Rules for AI coding agents\" section in pages/docs/index.md");
const index = docs.map((p) => `- [${p.title}](references/docs/${file(p.href)}.md) (${p.group}): ${read(p.href).description}`).join("\n");

const template = readFileSync(`${ROOT}scripts/skill/SKILL.md`, "utf8");
const skill = template
  .replaceAll("{{pieces}}", String(pieces.length))
  .replace("{{rules}}", rules)
  .replace("{{docs}}", index);
if (/\{\{\w+\}\}/.test(skill)) throw new Error(`skill: a placeholder is left in SKILL.md: ${/\{\{\w+\}\}/.exec(skill)![0]}`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(`${OUT}/references/docs`, { recursive: true });
writeFileSync(`${OUT}/SKILL.md`, skill);
writeFileSync(`${OUT}/references/pieces.md`, catalog);
for (const p of docs) {
  const { description, body } = read(p.href);
  writeFileSync(
    `${OUT}/references/docs/${file(p.href)}.md`,
    `<!-- Generated by scripts/skill.ts from site/src/pages/docs/${file(p.href)}.md. Online: ${SITE}${p.href} -->\n# ${p.title}\n\n${description}\n\n${plain(body, SITE)}\n`,
  );
}
console.log(`skill: SKILL.md, ${pieces.length} pieces, ${docs.length} docs pages`);

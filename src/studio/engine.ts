import type { Env, Frame, Meta, Piece } from "../types.ts";
import {
  buildLut,
  DOTS_RAMP,
  hexToRgb,
  shadeCell,
} from "./halftone.ts";
import { createLayerInstance } from "./layers/registry.ts";
import type {
  LayerInstance,
  RenderContext,
  SceneSpec,
  StudioSession,
} from "./types.ts";

const COLS = 200;
const ROWS = 100;
const TOTAL_CELLS = COLS * ROWS;

/** Compiles a declarative SceneSpec into an executable ascii.rest Piece. */
export function compileSceneToPiece(spec: SceneSpec): Piece {
  const meta: Meta = {
    name: spec.name,
    category: "scenes",
    note: spec.note ?? "procedural scene generated by ascii.rest studio",
    cols: COLS,
    rows: ROWS,
    cell: 1,
    fps: spec.fps ?? 15,
    ground: spec.ground,
    palette: [...spec.palette],
  };

  const paletteRgb = spec.palette.map(hexToRgb);
  const groundRgb = hexToRgb(spec.ground);
  const { nearest } = buildLut(paletteRgb);

  // Instantiated layer runners
  const layerInstances: { instance: LayerInstance; layer: (typeof spec.layers)[0] }[] = [];
  const ctx: RenderContext = {
    t: 0,
    cols: COLS,
    rows: ROWS,
    groundRgb,
    paletteRgb,
    nearestColor: nearest,
  };

  for (const l of spec.layers) {
    if (!l.enabled) continue;
    const inst = createLayerInstance(l.type);
    inst.init(ctx, l.params);
    layerInstances.push({ instance: inst, layer: l });
  }

  // Pre-allocated frame buffers
  const bufR = new Float32Array(TOTAL_CELLS);
  const bufG = new Float32Array(TOTAL_CELLS);
  const bufB = new Float32Array(TOTAL_CELLS);
  const bufDepth = new Float32Array(TOTAL_CELLS);
  const outChars: string[] = new Array(TOTAL_CELLS);

  const makeFrame = (): Frame => {
    return (t: number, env?: Env): string => {
      ctx.t = t;

      // Clear buffers to base ground color and infinite depth
      for (let i = 0; i < TOTAL_CELLS; i++) {
        bufR[i] = groundRgb[0];
        bufG[i] = groundRgb[1];
        bufB[i] = groundRgb[2];
        bufDepth[i] = 1000.0;
      }

      // Render layers from back to front
      for (let i = 0; i < layerInstances.length; i++) {
        const { instance, layer } = layerInstances[i];
        instance.render(ctx, layer.params, bufR, bufG, bufB, bufDepth);
      }

      // Halftone rasterization and color resolution pass
      const colorBuf = env?.color;
      const ramp = spec.halftone?.ramp ?? DOTS_RAMP;
      const dither = spec.halftone?.dither ?? "bayer4";
      const contrast = spec.halftone?.contrast ?? 1.0;

      for (let r = 0; r < ROWS; r++) {
        for (let x = 0; x < COLS; x++) {
          const idx = r * COLS + x;
          const { char, colorIdx } = shadeCell(
            bufR[idx],
            bufG[idx],
            bufB[idx],
            x,
            r,
            nearest,
            { ramp, dither, contrast }
          );

          outChars[idx] = char;
          if (colorBuf) {
            colorBuf[idx] = colorIdx;
          }
        }
      }

      return outChars.join("");
    };
  };

  return {
    meta,
    default: makeFrame,
  };
}

/** Creates a live interactive studio session for real-time scene tweaking. */
export function createStudioSession(initialSpec: SceneSpec): StudioSession {
  let currentSpec = JSON.parse(JSON.stringify(initialSpec)) as SceneSpec;
  let activePiece = compileSceneToPiece(currentSpec);
  let activeFrameFn = activePiece.default();

  const rebuild = () => {
    activePiece = compileSceneToPiece(currentSpec);
    activeFrameFn = activePiece.default();
  };

  return {
    get spec() {
      return currentSpec;
    },
    get piece() {
      return activePiece;
    },
    setParam(layerId: string, paramKey: string, value: any) {
      const target = currentSpec.layers.find((l) => l.id === layerId);
      if (target) {
        target.params[paramKey] = value;
        rebuild();
      }
    },
    toggleLayer(layerId: string, enabled?: boolean) {
      const target = currentSpec.layers.find((l) => l.id === layerId);
      if (target) {
        target.enabled = enabled ?? !target.enabled;
        rebuild();
      }
    },
    updatePalette(palette: string[], ground?: string) {
      currentSpec.palette = [...palette];
      if (ground) currentSpec.ground = ground;
      rebuild();
    },
    getFrame(t: number): string {
      return activeFrameFn(t);
    },
  };
}
